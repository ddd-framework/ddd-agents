<?php

declare(strict_types=1);

namespace DDD\Presentation\Api\Agents\Conversations\Dtos;

use DDD\Domain\AI\Entities\Conversations\AIConversation;
use DDD\Infrastructure\Base\DateTime\DateTime;
use DDD\Presentation\Base\Dtos\RestResponseDto;
use DDD\Presentation\Base\OpenApi\Attributes\Parameter;

/**
 * What a polling client needs to see that a conversation changed, without its messages: the run state, the owed-turn
 * mark, the newest stored message id and the display title and summary. A change of any of them is a change signal;
 * `lastMessageId` shows a new message while the run state stays the same. Reads no lazy relation: the summary is the
 * stored one (never generated by this read), null until the first summary was generated.
 *
 * @phpstan-consistent-constructor
 */
class AIConversationRunStateGetResponseDto extends RestResponseDto
{
    /** @var int The id of the AIConversation. */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public int $id;

    /** @var string The run state (IDLE, QUEUED, RUNNING, AWAITING_DELEGATES, COMPLETED, FAILED, CANCELLED). */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public string $runState;

    /** @var DateTime|null Set while the server owes a turn on an IDLE conversation; an IDLE conversation with it counts as running. */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public ?DateTime $agentTurnOwedAt = null;

    /** @var int|null The id of the newest stored message; null before the first. */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public ?int $lastMessageId = null;

    /** @var string|null The display title; null until the first title was generated. */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public ?string $title = null;

    /** @var bool Whether the owner set the title by hand (a generated title never replaces it then). */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public bool $titleManuallyEdited = false;

    /** @var string|null The generated summary text; null until the first summary was generated. */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public ?string $summary = null;

    /** @var DateTime|null When the conversation row was last modified. */
    #[Parameter(in: Parameter::RESPONSE, required: true)]
    public ?DateTime $updated = null;

    /**
     * The run state of `$conversation` as a polling client reads it. `lastMessageId` comes from the conversation's
     * computed {@see AIConversation::$lastMessageId} (null when the caller did not fill it). The summary is read only when
     * it is already loaded (`isset` never triggers its lazy generation).
     */
    public static function fromConversation(AIConversation $conversation): static
    {
        $aIConversationRunStateGetResponseDto = new static();
        $aIConversationRunStateGetResponseDto->id = (int)$conversation->id;
        $aIConversationRunStateGetResponseDto->runState = $conversation->runState;
        $aIConversationRunStateGetResponseDto->agentTurnOwedAt = isset($conversation->agentTurnOwedAt) ? $conversation->agentTurnOwedAt : null;
        $aIConversationRunStateGetResponseDto->lastMessageId = isset($conversation->lastMessageId) ? $conversation->lastMessageId : null;
        if (isset($conversation->summary)) {
            $aIConversationRunStateGetResponseDto->title = isset($conversation->summary->title) ? $conversation->summary->title : null;
            $aIConversationRunStateGetResponseDto->titleManuallyEdited = $conversation->summary->manuallyEdited;
            $aIConversationRunStateGetResponseDto->summary = isset($conversation->summary->text) ? $conversation->summary->text : null;
        }
        $aIConversationRunStateGetResponseDto->updated = $conversation->getModifiedTime();
        return $aIConversationRunStateGetResponseDto;
    }
}
