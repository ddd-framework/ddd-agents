<?php

declare(strict_types=1);

namespace DDD\Domain\AI\Entities\Conversations\Messages\Embeddings;

use DDD\Domain\AI\Entities\Conversations\Messages\AIConversationMessage;
use DDD\Domain\AI\Entities\Texts\Embeddings\TextEmbedding;
use DDD\Domain\AI\Repo\DB\Conversations\Messages\Embeddings\DBAIConversationMessageEmbedding;
use DDD\Domain\AI\Services\Conversations\AIConversationMessageEmbeddingsService;
use DDD\Domain\Base\Entities\ChangeHistory\ChangeHistoryTrait;
use DDD\Domain\Base\Entities\Entity;
use DDD\Domain\Base\Entities\LazyLoad\LazyLoad;
use DDD\Domain\Base\Entities\LazyLoad\LazyLoadRepo;
use DDD\Domain\Base\Entities\QueryOptions\QueryOptionsTrait;
use DDD\Domain\Base\Repo\DB\Database\DatabaseColumn;
use DDD\Domain\Base\Repo\DB\Database\DatabaseForeignKey;
use DDD\Domain\Base\Repo\DB\Database\DatabaseIndex;
use DDD\Domain\Common\Entities\MathEntities\Vector;
use DDD\Infrastructure\Traits\Serializer\Attributes\HideProperty;
use Symfony\Component\Validator\Constraints\NotNull;

/**
 * The semantic recall embedding of ONE {@see AIConversationMessage} — its own row in its own table, NOT a column on
 * the message. WHY a separate entity (the redesign that replaced the per-message `messageEmbedding` VECTOR column):
 * only a SUBSET of messages are recall units (TEXT with non-empty text); SIGNAL / tool-call / empty / nudge rows must
 * NOT carry a vector. A column on every message row forced a zero-vector on every non-recall row (MariaDB's vector
 * index forbids NULL), which broke the "is this embedded?" predicate in both directions (backfill `IS NULL` found
 * nothing, search `IS NOT NULL` matched every zero row) and bloated the heavy message table. As its OWN entity the
 * embedding simply DOESN'T EXIST for a non-recall message — absence of a row is the clean, indexable
 * "not embedded" sentinel (a normal LEFT JOIN / `IS NULL`), and the message table stays lean.
 *
 * Minimal row: exactly `aiConversationMessageId` (UNIQUE, the 1:1 parent FK) + the `embedding`. The conversation scope,
 * the index range and the account (for read-rights) are NOT denormalized here — a message-embedding is 1:1 with its
 * message, the vector search is message-rooted (it filters/scopes/groups on the MESSAGE), and the embedding's own
 * read-rights derive through `aiConversationMessage → aiConversation → account`. Lazy-loaded onto its message via
 * {@see AIConversationMessage::$messageEmbedding} (`addAsParent` — the message is this row's parent); off the message
 * hot path (only the recall search touches it). (Unlike {@see \DDD\Domain\AI\Entities\Conversations\Compaction\AIConversationCompactionNode},
 * which DOES carry `aiConversationId`/`coveredFrom..To` because a node spans many messages and is itself queried/ordered
 * by them — a 1:1 child needs none of that.)
 *
 * @method static AIConversationMessageEmbeddingsService getService()
 * @method static DBAIConversationMessageEmbedding getRepoClassInstance(string $repoType = null)
 */
// Exactly one embedding row per message (the embed seam upserts by this key; a redelivered async embed re-targets the
// same row instead of inserting a twin). This UNIQUE is also what makes the message↔embedding relation a 1:1 inverse.
#[DatabaseIndex(DatabaseIndex::TYPE_UNIQUE, ['aiConversationMessageId'])]
#[LazyLoadRepo(LazyLoadRepo::DB, DBAIConversationMessageEmbedding::class)]
class AIConversationMessageEmbedding extends Entity
{
    use ChangeHistoryTrait, QueryOptionsTrait;

    // NO `= null` defaults on persisted columns — a default makes the property always-initialized so the
    // upsert always writes it (defeating targeted single-column persists + turning a forgotten NOT-NULL set into a
    // NULL-violation rather than a clear uninitialized error). The service sets every column before persist.

    /** @var int|null Id of the {@see AIConversationMessage} this embedding belongs to (the parent). */
    #[NotNull]
    public ?int $aiConversationMessageId;

    /**
     * @var TextEmbedding|null The semantic embedding of the message text (`text-embedding-3-small`@1536) — the
     * per-message recall key. Generated by {@see AIConversationMessageEmbeddingsService::createEmbeddingForMessage} from the
     * message text, before persist. **NO `= null` default ON PURPOSE** (the EM zero-vector trap): a default makes the
     * {@see \DDD\Domain\Base\Repo\DB\Doctrine\DoctrineEntityManager} treat it as SET and write a ZERO vector; left
     * uninitialized the EM skips it. Here a row only ever EXISTS once embedded, so the vector is always real.
     * {@see HideProperty}: never serialize the 1536-float vector.
     */
    #[NotNull]
    #[DatabaseColumn(vectorDimensions: Vector::DIMENSION_OPENAI_EMBEDDING_SMALL)]
    #[HideProperty]
    public ?TextEmbedding $embedding;

    /** The parent message — `addAsParent`: this embedding is a child of its message (FK + cascade-delete with it). It is
     * also the path the read-rights account scope joins through (`→ aiConversation → account`). */
    #[DatabaseForeignKey(onDeleteAction: DatabaseForeignKey::ACTION_CASCADE, onUpdateAction: DatabaseForeignKey::ACTION_CASCADE)]
    #[LazyLoad(repoType: LazyLoadRepo::DB, addAsParent: true)]
    public ?AIConversationMessage $aiConversationMessage;

    /**
     * Whether the row holds a real vector — false for a row whose `embedding` is unset, empty or all zeros (the
     * column default a failed embedding call left before the writer refused to persist one). Pure.
     */
    public function hasVector(): bool
    {
        return isset($this->embedding) && !$this->embedding->isEmpty();
    }
}
