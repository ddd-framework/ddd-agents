<?php

declare(strict_types=1);

namespace DDD\Domain\AI\Entities\Conversations\Widgets\Composed;

use DDD\Domain\AI\Entities\Conversations\Widgets\Composed\DataSources\ComposedViewDataSourceClasses;
use DDD\Domain\AI\Entities\Conversations\Widgets\Composed\EntityReferences\EntityReferenceResolverClasses;
use DDD\Domain\AI\Entities\Conversations\Widgets\ConversationWidgetClasses;
use stdClass;

/**
 * THE one schema of the `ComposedView` kit: every node type's categories, props and slots,
 * the budgets, the categories, size classes and action types, the finding codes (those that drop nothing as
 * `noteFindingCodes`), the embeddable domain widgets, the registered data
 * sources and the entity types — built from the node
 * classes and exported into the committed `composed-node-schema.json` that the frontend types, the frontend parser and
 * the model-facing spec read. One list, no second copy: parity tests on both sides fail when the file is stale
 * (a parity test of the application, the frontend `_composed-node-schema.spec.ts`). Regenerated by the integrator
 * from {@see buildJson()} (a shared generated file). Reads nothing.
 */
class ComposedViewNodeSchema
{
    public const int SCHEMA_VERSION = 1;

    /** The committed file, relative to the repository root. */
    public const string SCHEMA_FILE_RELATIVE_PATH = 'html/react/src/components/ai-conversations/conversation-markdown/widget-tree/composed-node-schema.json';

    /** @return array<string, mixed> the schema, keys in a fixed order */
    public static function build(): array
    {
        $nodeTypes = [];
        foreach (ComposedViewNodeClasses::getNodeClassesByNodeType() as $nodeType => $nodeClass) {
            $nodeTypes[$nodeType] = [
                'categories' => array_values($nodeClass::CATEGORIES),
                'providesItemScope' => $nodeClass::PROVIDES_ITEM_SCOPE,
                'textContentProp' => $nodeClass::getTextContentPropName(),
                'summary' => $nodeClass::SUMMARY,
                'props' => array_map(static fn (ComposedViewNodeProp $prop): array => $prop->toSchemaArray(), $nodeClass::getPropDeclarations()),
                'slots' => array_map(static fn (ComposedViewNodeSlot $slot): array => $slot->toSchemaArray(), $nodeClass::getSlotDeclarations()),
            ];
            $sourcing = $nodeClass::buildSourcingSchemaArray();
            if ($sourcing !== null) {
                $nodeTypes[$nodeType]['sourcing'] = $sourcing;
            }
            $nodeTypes[$nodeType] += $nodeClass::buildStateRulesSchemaArray();
        }
        $embeddableWidgets = [];
        $widgetTypes = array_map('strval', array_keys(ConversationWidgetClasses::getWidgetClassesByWidgetType()));
        sort($widgetTypes);
        foreach (ConversationWidgetClasses::getWidgetClassesByWidgetType() as $widgetType => $widgetClass) {
            if ($widgetClass::EMBEDDABLE) {
                $embeddableWidgets[$widgetType] = ['sizeClass' => $widgetClass::EMBEDDED_SIZE_CLASS];
            }
        }
        return [
            'version' => self::SCHEMA_VERSION,
            'generatedBy' => 'ComposedViewNodeSchema::buildJson() — never edit by hand',
            'budgets' => ComposedViewBudgets::toSchemaArray(),
            'categories' => ComposedViewNodeCategory::ALL,
            'sizeClasses' => ComposedViewNodeSlot::SIZE_CLASSES,
            'actionTypes' => ComposedViewTreeReading::ACTION_TYPES,
            'bindingKinds' => ComposedViewBinding::KINDS,
            'findingCodes' => [
                ComposedViewValidationFinding::CODE_INVALID_NODE,
                ComposedViewValidationFinding::CODE_INVALID_PROP,
                ComposedViewValidationFinding::CODE_UNKNOWN_BINDING,
                ComposedViewValidationFinding::CODE_INVALID_EXPRESSION,
                ComposedViewValidationFinding::CODE_INVALID_STATE,
                ComposedViewValidationFinding::CODE_INVALID_ACTION,
                ComposedViewValidationFinding::CODE_BUDGET_EXCEEDED,
                ComposedViewValidationFinding::CODE_INLINE_VALUE_WITHOUT_SOURCE,
                ComposedViewValidationFinding::CODE_INVALID_INITIAL_CHOICE,
                ComposedViewValidationFinding::CODE_UNREAD_STATE,
                ComposedViewValidationFinding::CODE_UNKNOWN_ITEM_KEY,
                ComposedViewValidationFinding::CODE_INVALID_SLOT_NODE_COUNT,
                ComposedViewValidationFinding::CODE_WIDGET_LIFTED,
            ],
            'noteFindingCodes' => ComposedViewValidationFinding::NOTE_CODES,
            'nodeTypes' => $nodeTypes !== [] ? $nodeTypes : new stdClass(),
            'embeddableWidgets' => $embeddableWidgets !== [] ? $embeddableWidgets : new stdClass(),
            // every registered widget type: a `Widget` node naming one its slot refuses is lifted, an unknown one dropped
            'widgetTypes' => $widgetTypes,
            'dataSources' => ($dataSources = ComposedViewDataSourceClasses::toSchemaArray()) !== [] ? $dataSources : new stdClass(),
            'entityTypes' => EntityReferenceResolverClasses::getEntityTypes(),
        ];
    }

    /** The schema as the committed file holds it: pretty JSON, unescaped slashes and unicode, one trailing newline. */
    public static function buildJson(): string
    {
        return json_encode(static::build(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n";
    }
}
